#!/usr/bin/env python3
"""Convert a raw little-endian binary image into rtl/myxtrv32_rom.v.

The ROM is emitted as a fully initialised register array so that both
simulation (xsim/Verilog) and synthesis (Vivado) see exactly the same
contents without relying on $readmemh search paths.

By default the words past the end of the image are filled with a distinct
per-address pattern.  This is deliberate: Vivado folds long runs of zeros
into constant logic and then implements only the used part of the ROM with
a couple of RAMB18s plus LUTs.  Filling every word keeps the array
"content-carrying", which makes the tools map the full 4096x32 array into
Block RAM as requested by the MyXTRV32 v0.1 memory plan.
Use --fill zero to get the compact (LUT optimised) implementation instead.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

HEADER = """\
//============================================================================
//  MyXTRV32 instruction ROM  -- AUTO-GENERATED, DO NOT EDIT
//  generated by scripts/gen_rom.py from {src}
//  image size: {size} bytes ({used} used of {total} words, fill={fill})
//
//  Two independent read ports:
//    iaddr/idata : instruction fetch (port A)
//    daddr/ddata : data loads from the 0x0000_0000..0x0000_3FFF window
//============================================================================
`timescale 1ns / 1ps
`default_nettype none

module myxtrv32_rom #(
    parameter integer WORDS = {total}
) (
    input  wire        clk,
    input  wire [13:0] iaddr,
    output reg  [31:0] idata,
    input  wire [13:0] daddr,
    output reg  [31:0] ddata
);

    (* rom_style = "block" *) reg [31:0] mem [0:WORDS-1];

    initial begin
"""

FOOTER = """\
    end

    always @(posedge clk) begin
        idata <= mem[iaddr];
        ddata <= mem[daddr];
    end

endmodule

`default_nettype wire
"""


def fill_pattern(i: int) -> int:
    """Deterministic, distinct value per word (marks unused ROM locations)."""
    return (0xDEAD0000 | ((i * 0x9E3779B1) & 0xFFFF)) & 0xFFFFFFFF


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("bin", type=Path, help="raw binary image (little endian)")
    ap.add_argument("out", type=Path, help="output verilog file")
    ap.add_argument("--words", type=int, default=16384, help="ROM depth in 32-bit words")
    ap.add_argument("--fill", choices=["pattern", "zero"], default="pattern",
                    help="content past the image; 'pattern' forces a full BRAM mapping")
    args = ap.parse_args()

    data = args.bin.read_bytes()
    if len(data) > args.words * 4:
        print(f"error: image is {len(data)} bytes, ROM holds {args.words * 4}", file=sys.stderr)
        return 1

    if len(data) % 4:
        data += b"\x00" * (4 - len(data) % 4)

    used = len(data) // 4
    words = list(struct.unpack("<%dI" % used, data)) if used else []

    if args.fill == "pattern":
        while len(words) < args.words:
            words.append(fill_pattern(len(words)))
        used = len(words)
    else:
        # only the image words are emitted; the rest reads back as zero
        pass

    lines = []
    for i in range(0, len(words), 4):
        chunk = words[i : i + 4]
        body = " ".join(f"mem[{i + j:4d}] = 32'h{w:08X};" for j, w in enumerate(chunk))
        lines.append("        " + body)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", encoding="ascii", newline="\n") as fh:
        fh.write(HEADER.format(src=args.bin.name, size=len(data), used=used,
                               total=args.words, fill=args.fill))
        fh.write("\n".join(lines))
        fh.write("\n")
        fh.write(FOOTER)
    print(f"[gen_rom] {args.out}  ({used} words used of {args.words}, fill={args.fill})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
