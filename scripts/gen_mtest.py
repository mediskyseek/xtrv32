#!/usr/bin/env python3
"""Generate sw/mtest.c -- a self-checking M-extension test firmware.

Reference values are computed here (Python, 64-bit) so the test never relies
on the instructions it is checking.
"""
from __future__ import annotations

import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sw" / "mtest.c"

M32 = 0xFFFFFFFF


def s32(x: int) -> int:
    x &= M32
    return x - (1 << 32) if x & 0x80000000 else x


def trunc_div(a: int, b: int) -> int:
    q = abs(a) // abs(b)
    return -q if (a < 0) ^ (b < 0) else q


def enc(*pairs) -> list[tuple[int, int]]:
    return [(a & M32, b & M32) for a, b in pairs]


VECTORS: list[tuple[int, int]] = []
VECTORS += enc(
    (0, 0), (1, 1), (0, 1), (1, 0),
    (0x12345678, 0x9ABCDEF0),
    (0xFFFFFFFF, 0xFFFFFFFF),
    (0x7FFFFFFF, 0x7FFFFFFF),
    (0x80000000, 0x80000000),
    (0x80000000, 0xFFFFFFFF),
    (0x80000001, 0xFFFFFFFF),
    (0x7FFFFFFF, 0xFFFFFFFF),
    (0x0000FFFF, 0x00010001),
    (0xFFFF0000, 0x0000FFFF),
    (0xDEADBEEF, 0xCAFEBABE),
    (0x00000001, 0xFFFFFFFF),
    (0xFFFFFFFF, 0x00000001),
)

random.seed(20261104)
while len(VECTORS) < 48:
    a = random.getrandbits(32)
    b = random.getrandbits(32)
    VECTORS.append((a, b))

rows = []
for a, b in VECTORS:
    sa, sb = s32(a), s32(b)
    mul = (a * b) & M32
    mulh = ((sa * sb) >> 32) & M32
    mulhsu = ((sa * (b & M32)) >> 32) & M32
    mulhu = ((a * b) >> 32) & M32
    if b == 0:
        div = rem = 0xFFFFFFFF if False else 0  # filled below
        divv = remv = dvu = rmu = 0
        note = 1
    else:
        note = 0
        q = trunc_div(sa, sb)
        div = q & M32
        rem = (sa - q * sb) & M32
        dvu = ((a & M32) // (b & M32)) & M32
        rmu = ((a & M32) % (b & M32)) & M32
    rows.append((a, b, mul, mulh, mulhsu, mulhu, div, rem, dvu, rmu, note))

table = "\n".join(
    "    { 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, %d },"
    % r
    for r in rows
)

src = f"""/*============================================================================
 *  MyXTRV32 M-extension self test  -- AUTO-GENERATED by scripts/gen_mtest.py
 *  Each row: {{ a, b, mul, mulh, mulhsu, mulhu, div, rem, divu, remu, skip_div }}
 *  skip_div = 1 means b == 0 (division by zero is checked separately).
 *============================================================================*/
#include <stdint.h>

extern void uart_send_char(char c);

static void putc_(char c) {{ uart_send_char(c); }}
static void puts_(const char *s) {{ while (*s) putc_(*s++); }}

static const char hexd[] = "0123456789ABCDEF";
static void puthex(uint32_t v)
{{
    int i;
    for (i = 28; i >= 0; i -= 4)
        putc_(hexd[(v >> i) & 0xF]);
}}

static void putdec(uint32_t v)
{{
    char buf[11];
    int  n = 0;
    if (v == 0) {{ putc_('0'); return; }}
    while (v) {{ buf[n++] = (char)('0' + (v % 10)); v /= 10; }}
    while (n) putc_(buf[--n]);
}}

static inline uint32_t rv_mul(uint32_t a, uint32_t b)
{{ uint32_t r; __asm__ volatile("mul    %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_mulh(int32_t a, int32_t b)
{{ uint32_t r; __asm__ volatile("mulh   %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_mulhsu(int32_t a, uint32_t b)
{{ uint32_t r; __asm__ volatile("mulhsu %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_mulhu(uint32_t a, uint32_t b)
{{ uint32_t r; __asm__ volatile("mulhu  %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_div(int32_t a, int32_t b)
{{ uint32_t r; __asm__ volatile("div    %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_rem(int32_t a, int32_t b)
{{ uint32_t r; __asm__ volatile("rem    %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_divu(uint32_t a, uint32_t b)
{{ uint32_t r; __asm__ volatile("divu   %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}
static inline uint32_t rv_remu(uint32_t a, uint32_t b)
{{ uint32_t r; __asm__ volatile("remu   %0,%1,%2" : "=r"(r) : "r"(a), "r"(b)); return r; }}

typedef struct {{
    uint32_t a, b;
    uint32_t mul, mulh, mulhsu, mulhu;
    uint32_t div, rem, divu, remu;
    uint32_t skip_div;
}} vec_t;

static const vec_t vec[] = {{
{table}
}};

static uint32_t fails;

static void expect(const char *op, uint32_t a, uint32_t b, uint32_t got, uint32_t exp)
{{
    if (got != exp)
    {{
        fails++;
        puts_("FAIL ");
        puts_(op);
        puts_(" a="); puthex(a);
        puts_(" b="); puthex(b);
        puts_(" got="); puthex(got);
        puts_(" exp="); puthex(exp);
        puts_("\\r\\n");
    }}
}}

int main(void)
{{
    unsigned i;

    for (i = 0; i < sizeof(vec) / sizeof(vec[0]); i++)
    {{
        const vec_t *v = &vec[i];
        expect("mul",    v->a, v->b, rv_mul(v->a, v->b),        v->mul);
        expect("mulh",   v->a, v->b, rv_mulh((int32_t)v->a, (int32_t)v->b), v->mulh);
        expect("mulhsu", v->a, v->b, rv_mulhsu((int32_t)v->a, v->b), v->mulhsu);
        expect("mulhu",  v->a, v->b, rv_mulhu(v->a, v->b),      v->mulhu);
        if (!v->skip_div)
        {{
            expect("div",  v->a, v->b, rv_div((int32_t)v->a, (int32_t)v->b), v->div);
            expect("rem",  v->a, v->b, rv_rem((int32_t)v->a, (int32_t)v->b), v->rem);
            expect("divu", v->a, v->b, rv_divu(v->a, v->b),     v->divu);
            expect("remu", v->a, v->b, rv_remu(v->a, v->b),     v->remu);
        }}
    }}

    /* division by zero: quotient = -1, remainder = dividend */
    expect("div0",  0x12345678u, 0, rv_div(0x12345678, 0),        0xFFFFFFFFu);
    expect("rem0",  0x12345678u, 0, rv_rem(0x12345678, 0),        0x12345678u);
    expect("divu0", 0x12345678u, 0, rv_divu(0x12345678u, 0),      0xFFFFFFFFu);
    expect("remu0", 0x12345678u, 0, rv_remu(0x12345678u, 0),      0x12345678u);

    /* signed overflow: INT_MIN / -1 */
    expect("divovf",  0x80000000u, 0xFFFFFFFFu, rv_div(-2147483647 - 1, -1), 0x80000000u);
    expect("removf",  0x80000000u, 0xFFFFFFFFu, rv_rem(-2147483647 - 1, -1), 0x00000000u);

    if (fails == 0)
    {{
        puts_("M EXT PASS (");
        putdec(sizeof(vec) / sizeof(vec[0]));
        puts_(" vectors)\\r\\n");
    }}
    else
    {{
        puts_("M EXT FAIL count=");
        putdec(fails);
        puts_("\\r\\n");
    }}

    for (;;)
        ;
}}
"""

OUT.write_text(src)
print(f"[gen_mtest] {OUT}  ({len(VECTORS)} vectors)")


# --- quick self-check of the Python reference model -----------------------
def check_model() -> None:
    assert trunc_div(-7, 2) == -3
    assert trunc_div(7, -2) == -3
    assert trunc_div(-7, -2) == 3
    assert s32(0x80000000) == -2147483648
    for a, b in VECTORS:
        sa, sb = s32(a), s32(b)
        if sb:
            q = trunc_div(sa, sb)
            assert (q * sb + (sa - q * sb)) == sa
    print("[gen_mtest] model sanity OK")


check_model()
